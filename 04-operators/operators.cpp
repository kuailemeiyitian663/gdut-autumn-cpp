/*
 * 04 运算符
 * 一句话要点：p++ 是先拿旧值再加，++q 是先加再拿新值；&& 左边为假时右边根本不算（短路）；
 * && / || 短路；位运算 << 左移等于乘 2；* 和 / % 比 + 高一级，先算乘除后算加减。
 */
#include <iostream>
using namespace std;

int main() {
    int a = 6, b = 4;

    // 1. 算术运算符
    cout << "a+b=" << a + b << "   a-b=" << a - b << "   a*b=" << a * b << endl;
    cout << "a/b=" << a / b << "   a%b=" << a % b << endl;   // % 取余，只能对整数用

    // 2. 自增自减：前后置区别（机试必考）
    int p = 3, q = 3;
    cout << "p++ = " << p++ << "   之后 p = " << p << "   <- 后置：先用旧值" << endl;
    cout << "++q = " << ++q << "   之后 q = " << q << "   <- 前置：先加再用" << endl;

    // 3. 关系 + 逻辑
    cout << "(a>b)      = " << (a > b) << endl;
    cout << "a>b && b<10= " << (a > b && b < 10) << endl;
    cout << "a>b || a<3 = " << (a > b || a < 3) << endl;
    cout << "!(a>b)     = " << !(a > b) << endl;

    // 4. 短路：左边为假，右边压根不执行
    int t = 0;
    bool r = (a < b) && (++t > 0);
    cout << "短路之后 t = " << t << "   <- 还是 0，说明右边根本没运行" << endl;

    // 5. 三元运算符
    int maxv = (a > b) ? a : b;
    cout << "max = " << maxv << endl;

    // 6. 复合赋值
    int s = 10;
    s += 5; s -= 3; s *= 2;
    cout << "s = " << s << endl;

    // 7. 位运算（嵌入式岗也常考，顺手练）
    cout << "6 & 4 = " << (6 & 4) << "     6|4 = " << (6 | 4) << "     6^4 = " << (6 ^ 4) << endl;
    cout << "6 << 1 = " << (6 << 1) << "    << 左移一位 = 乘 2" << endl;

    // 8. 运算符优先级坑
    cout << "10 + 8/2 = " << 10 + 8 / 2 << "     <- 先算除，得 14 不是 9" << endl;

    return 0;
}

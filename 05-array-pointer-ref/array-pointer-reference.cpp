/*
 * 05 数组 / 指针 / 引用（机试最难的一块，也是最能拉开差距的一块）
 * 一句话要点：数组名在绝大多数情况就等于首元素地址（arr 和 &arr[0] 同一个东西）；
 * 指针 + 1 走的是一个元素的大小（int* 加 1 跳 4 字节），不是跳 1 字节；
 * 引用是别名不是新变量，改 r 就是改 y。
 */
#include <iostream>
using namespace std;

int main() {
    // ============ 数组 ============
    int arr[5] = {10, 20, 30, 40, 50};

    // 数组名即首地址：arr == &arr[0]
    cout << "arr     = " << arr << endl;
    cout << "&arr[0] = " << &arr[0] << "   <- 两个是一样的地址" << endl;

    for (int i = 0; i < 5; i++) {
        cout << "arr[" << i << "] = " << arr[i]
             << "   用指针写 *(arr+" << i << ") = " << *(arr + i) << endl;
    }

    // 经典坑：越界编译不报错，运行时可能崩
    // arr[5] = 999;   // ← 别放开，越界写很危险

    // ============ 指针 ============
    int x = 100;
    int* p = &x;                 // p 存 x 的地址
    cout << "x = " << x << "   *p = " << *p << "   p = " << p << endl;
    *p = 200;                    // 通过指针改掉外面的值
    cout << "改完之后 x = " << x << endl;

    // 指针的步长按类型走：int* 加 1 跳 4 字节
    int* q = arr;
    cout << "q    = " << q << endl;
    cout << "q+1  = " << (q + 1) << "   <- 地址差了 4，不是 1" << endl;

    // 用指针遍历整个数组
    cout << "指针遍历: ";
    for (int* it = arr; it < arr + 5; ++it) {
        cout << *it << " ";
    }
    cout << endl;

    // ============ 引用 ============
    int y = 5;
    int& r = y;                  // r 就是 y 的别名
    r = 50;
    cout << "改 r 之后 y = " << y << "（y 也变成 50 了）" << endl;
    cout << "&y 和 &r 同一地址? " << (&y == &r ? "true" : "false") << endl;

    // 引用的坑：定义时必须初始化
    // int& bad;   // 编译报错

    // ============ 加分项：数组指针 ============
    // int (*rowPtr)[5] = &arr;   行指针：指向一个"含 5 个 int 的数组"
    // (*rowPtr)[3]  == arr[3]
    return 0;
}

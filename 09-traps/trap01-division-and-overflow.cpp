// =========================================================
// 机试坑 01：整数运算（除法截断 / 取模负数 / short 溢出 / 除零）
// 对应考纲：变量、运算符、类型转换
// 编译运行：g++ -std=c++11 -Wall -o trap01 trap01-division-and-overflow.cpp
// =========================================================
#include <iostream>
using namespace std;

int main() {
    // ========== 坑 1：整数除法是"截断"，不是四舍五入 ==========
    int a = 5, b = 2;
    cout << "5 / 2        = " << (5 / 2)
         << "   <- 整数除法，小数被直接抹掉，得 2 不是 2.5" << endl;
    cout << "5.0 / 2      = " << (5.0 / 2)
         << "   <- 只要有一个操作数是浮点，就正常除，得 2.5" << endl;

    // 机试最高频翻车：算平均值用 (a+b)/2，个位直接丢
    cout << "(5+2) / 2    = " << ((5 + 2) / 2) << "   <- 直接算平均，精度丢了" << endl;
    cout << "1.0*(5+2)/2  = " << (1.0 * (5 + 2) / 2) << "   <- 正确写法：先转成浮点" << endl;
    cout << "              (也可以写 (5+2)/2.0，效果一样)" << endl;

    // ========== 坑 2：取模和除法跟着负数走正负 ==========
    int m = -7;
    cout << "-7 % 3       = " << (m % 3) << "   <- 得 -1，跟 7%3=1 不一样" << endl;
    cout << "-7 / 3       = " << (m / 3) << "   <- 向零取整，得 -2，不是 -3" << endl;
    cout << "              （C++ 里负数除法是「向零靠拢」，不是「向下取整」，跟 Python 不一样）" << endl;

    // ========== 坑 3：溢出不报错，只是悄悄绕回去 ==========
    // int 最大 2147483647，加 1 直接变成 -2147483648，机器不给你任何提示
    // 机试里最常见的是"计数超过 3 万多还用 short"
    short s = 32767;                       // short（16 位）上限是 32767
    cout << "short 上限    = " << s
         << "  -> +1 后 = " << (short)(s + 1) << "   <- 绕回 -32768" << endl;
    cout << "              （存人数、存下标、存循环计数，一律用 int，别省内存用 short）" << endl;

    // ========== 坑 4：除以 0 会崩，而且整数/浮点死法不同 ==========
    // int zero = 0;  int c = 5 / zero;        // 整数除 0：运行期直接崩，机试当场挂
    // double z = 0.0; double d = 1.0 / z;     // 浮点除 0：得 inf，不崩但后面全是垃圾数
    cout << "（除零那两行已注释）" << endl;
    cout << "              （机试看到「分母可能是 0」，第一步先加 if (den != 0) 判一下）" << endl;

    return 0;
}
